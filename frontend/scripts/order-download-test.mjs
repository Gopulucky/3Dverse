import assert from 'node:assert/strict';
import { loadTs } from './load-ts.mjs';
const { canDownloadModel } = await loadTs('src/lib/order-download.ts');
const order = { status: 'paid', currency: 'INR', payment_verified_at: '2026-10-29T12:00:00Z' };
const item = { product_id: 1, selected_config: { purchase_type: 'digital' } };
assert.equal(canDownloadModel(order, item), true);
assert.equal(canDownloadModel({ ...order, payment_verified_at: null }, item), false);
assert.equal(canDownloadModel({ ...order, status: 'pending_payment' }, item), false);
assert.equal(canDownloadModel({ ...order, status: 'cancelled' }, item), false);
assert.equal(canDownloadModel(order, { ...item, selected_config: { purchase_type: 'physical' } }), false);
assert.equal(canDownloadModel({ status: 'paid', currency: 'USD' }, item), true);
const legacyItem = { product_id: 1, product: { is_mode_2_active: true, digital_download_enabled: true } };
assert.equal(canDownloadModel({ status: 'paid', currency: 'USD' }, legacyItem), true);
assert.equal(canDownloadModel({ status: 'paid', currency: 'USD' }, { ...legacyItem, product: { ...legacyItem.product, is_mode_3_active: true } }), false);
assert.equal(canDownloadModel(order, legacyItem), false);
console.log('Download visibility checks passed: verified digital INR, explicit and unambiguous legacy USD, no physical/unpaid access.');
